// Joins styles-parts/*.css and ui/js/features/*/*.css into ui/styles.css.
// Edit files in styles-parts/ or ui/js/features/, never ui/styles.css directly.

import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const partsDir = join(root, 'styles-parts');
const outFile = join(root, 'ui', 'styles.css');

const parts = existsSync(partsDir)
  ? readdirSync(partsDir).filter((n) => n.endsWith('.css')).sort()
  : [];

if (parts.length === 0) {
  console.error('build-styles: no files found in styles-parts/');
  process.exit(1);
}

const banner = '/* GENERATED by scripts/build-styles.mjs from styles-parts and feature CSS files. Do not edit directly. */\n';
const body = parts.map((name) => readFileSync(join(partsDir, name), 'utf8')).join('\n');

const featuresDir = join(root, 'ui', 'js', 'features');
let featureStyles = '';
if (existsSync(featuresDir)) {
  const dirs = readdirSync(featuresDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .sort((a, b) => a.name.localeCompare(b.name));
  for (const d of dirs) {
    const fPath = join(featuresDir, d.name);
    const cssFiles = readdirSync(fPath)
      .filter((f) => f.endsWith('.css') && f !== 'overlay.css')
      .sort();
    for (const cf of cssFiles) {
      featureStyles += `\n/* Feature: ${d.name}/${cf} */\n` + readFileSync(join(fPath, cf), 'utf8');
    }
  }
}

const next = banner + body + featureStyles;
const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : null;
if (current !== next) {
  writeFileSync(outFile, next);
  console.log(`build-styles: wrote ui/styles.css from ${parts.length} parts`);
} else {
  console.log('build-styles: ui/styles.css already up to date');
}
